# home-assistant/tools/build-hooks.py -- plan task 1.6: generates the bundle's <name>.compile.py hooks.
#
# A compile hook is one sandboxed file, so code the seven hooks share can't be a library they import. It lives once in
# home-assistant/hooks/, and this tool writes each hook from hooks/<name>.py, expanding two directives:
#
#   #@include <file>                      the file from hooks/, in place
#   #@include-lib <module>.py <name> ...  the named top-level definitions from the bundle's lib/<module>.py, verbatim,
#                                         so the hook and the board run the same code (ha_device's size check uses
#                                         ts_ha.build_discovery)
#
#   python3 home-assistant/tools/build-hooks.py           write the hooks
#   python3 home-assistant/tools/build-hooks.py --check   exit 1, naming each hook that's out of date; write nothing
#
# The generated hooks are committed (a user copies the bundle as it is). Stdlib only.

import ast
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOOKS = os.path.join(ROOT, 'hooks')
BUNDLE = os.path.join(ROOT, 'home-assistant')
HEADER = ('# GENERATED by home-assistant/tools/build-hooks.py from home-assistant/hooks/%s -- don\'t edit this file:\n'
          '# edit hooks/ (or lib/ for included definitions) and run the tool.\n\n')


class BuildError(Exception):
    pass


def _lib_definitions(module, names, where):
    path = os.path.join(BUNDLE, 'lib', module)
    with open(path, encoding='utf-8') as f:
        source = f.read()
    found = {}
    for node in ast.parse(source).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            found[node.name] = node
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    found[t.id] = node
    out = []
    for name in names:
        if name not in found:
            raise BuildError('%s: lib/%s has no top-level %r' % (where, module, name))
        out.append(ast.get_source_segment(source, found[name]))
    return ('# -- from lib/%s: %s --\n\n' % (module, ', '.join(names))) + '\n\n\n'.join(out) + '\n'


def expand(name):
    path = os.path.join(HOOKS, name)
    with open(path, encoding='utf-8') as f:
        lines = f.read().splitlines()
    out = []
    for i, line in enumerate(lines, 1):
        where = 'hooks/%s line %d' % (name, i)
        if line.startswith('#@include-lib '):
            parts = line.split()[1:]
            if len(parts) < 2:
                raise BuildError('%s: #@include-lib needs a module and at least one name' % where)
            out.append('\n' + _lib_definitions(parts[0], parts[1:], where))
        elif line.startswith('#@include '):
            inc = line.split(None, 1)[1].strip()
            if not os.path.isfile(os.path.join(HOOKS, inc)):
                raise BuildError('%s: no hooks/%s to include' % (where, inc))
            with open(os.path.join(HOOKS, inc), encoding='utf-8') as f:
                out.append('\n' + f.read().rstrip('\n') + '\n')
        elif line.startswith('#@'):
            raise BuildError('%s: unknown directive %r' % (where, line.split()[0]))
        else:
            out.append(line)
    text = HEADER % name + '\n'.join(out).rstrip('\n') + '\n'
    compile(text, name, 'exec')  # a syntax error names the hook, not the editor's compile
    return text


def targets():
    names = sorted(n for n in os.listdir(HOOKS) if n.startswith('ha_') and n.endswith('.py'))
    if not names:
        raise BuildError('no hooks/ha_*.py found in %s' % HOOKS)
    for n in names:
        if not os.path.isfile(os.path.join(BUNDLE, n[:-3] + '.node.json')):
            raise BuildError('hooks/%s has no %s.node.json in the bundle' % (n, n[:-3]))
    return [(n, os.path.join(BUNDLE, n[:-3] + '.compile.py')) for n in names]


def main(argv):
    check = argv[1:] == ['--check']
    if argv[1:] not in ([], ['--check']):
        print('usage: build-hooks.py [--check]')
        return 2
    try:
        stale = []
        for name, dest in targets():
            text = expand(name)
            try:
                with open(dest, encoding='utf-8') as f:
                    current = f.read()
            except FileNotFoundError:
                current = None
            if current == text:
                continue
            stale.append(os.path.relpath(dest, ROOT))
            if not check:
                with open(dest, 'w', encoding='utf-8') as f:
                    f.write(text)
    except BuildError as e:
        print('build-hooks: %s' % e)
        return 1
    if check and stale:
        print('build-hooks: out of date, run home-assistant/tools/build-hooks.py: %s' % ', '.join(stale))
        return 1
    print('build-hooks: %s' % (('wrote ' + ', '.join(stale)) if stale else 'all hooks up to date'))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
